import java.rmi.Naming;
import java.rmi.RemoteException;
import java.rmi.server.UnicastRemoteObject;
import java.time.LocalTime;
import java.time.format.DateTimeFormatter;
import java.util.ArrayList;
import java.util.Collections;
import java.util.List;
import java.util.Random;
import javax.swing.*;
import javax.swing.border.*;
import java.awt.*;
import java.awt.event.*;

/**
 * RMIServer implements the remote interface and hosts a Swing dashboard
 * that logs every client request in real time.
 *
 * Run this FIRST, then launch up to 4 clients.
 */
public class RMIServer extends UnicastRemoteObject implements ServerInterface {

    // ── Shared state (all clients see the same list) ──────────────────────────
    private final List<String> sharedResources = Collections.synchronizedList(new ArrayList<>());
    private final List<String> serverLog       = Collections.synchronizedList(new ArrayList<>());

    // ── GUI components ─────────────────────────────────────────────────────────
    private JTextArea  logArea;
    private JTextArea  resourceArea;

    // ── Personality templates ──────────────────────────────────────────────────
    private static final String[] TRAITS   = {"creative", "analytical", "empathetic", "adventurous", "determined", "cheerful"};
    private static final String[] STRENGTHS = {"problem-solving", "communication", "leadership", "innovation", "teamwork"};
    private static final String[] QUOTES    = {
        "\"The only way to do great work is to love what you do.\"",
        "\"Life is what happens when you're busy making other plans.\"",
        "\"Be the change you wish to see in the world.\""
    };

    // ──────────────────────────────────────────────────────────────────────────
    public RMIServer() throws RemoteException {
        super();
        // Seed shared resources
        sharedResources.add("📄 Company Policy v2.pdf");
        sharedResources.add("📊 Q1 Sales Report.xlsx");
        sharedResources.add("🗂️  Project Timeline.docx");
        sharedResources.add("🔑 Server Config (read-only)");
    }

    // ═══════════════════════════  Remote Methods  ════════════════════════════

    @Override
    public List<String> getSharedResources() throws RemoteException {
        log("SYSTEM", "getSharedResources", "Client viewed shared resources");
        return new ArrayList<>(sharedResources);
    }

    @Override
    public void addSharedResource(String resource) throws RemoteException {
        sharedResources.add(resource);
        log("SYSTEM", "addSharedResource", "Added: " + resource);
        SwingUtilities.invokeLater(this::refreshResourcePanel);
    }

    @Override
    public String generatePersonality(String clientName, String fullName,
                                      int age, String hobbies, String favColor)
            throws RemoteException {

        log(clientName, "generatePersonality",
            "name=" + fullName + ", age=" + age + ", hobbies=" + hobbies);

        Random rnd = new Random(fullName.hashCode() + age);
        String trait    = TRAITS  [rnd.nextInt(TRAITS.length)];
        String strength = STRENGTHS[rnd.nextInt(STRENGTHS.length)];
        String quote    = QUOTES   [rnd.nextInt(QUOTES.length)];

        return String.format(
            "🌟 Personality Profile for %s 🌟\n" +
            "━━━━━━━━━━━━━━━━━━━━━━━━━━━\n" +
            "✨ Core Trait : %s\n" +
            "💪 Strength   : %s\n" +
            "🎨 Fav Colour : %s\n" +
            "🎯 Hobbies    : %s\n" +
            "🔢 Age Vibe   : %s\n" +
            "💬 Quote      : %s\n" +
            "━━━━━━━━━━━━━━━━━━━━━━━━━━━\n" +
            "Generated by CSC405 Server ✅",
            fullName, trait, strength, favColor, hobbies,
            age < 25 ? "Young explorer full of potential!" :
            age < 40 ? "Experienced professional in prime years!" :
                       "Wise veteran with a wealth of experience!",
            quote
        );
    }

    @Override
    public List<String> getServerLog() throws RemoteException {
        return new ArrayList<>(serverLog);
    }

    // ═══════════════════════════  Logging Utility  ══════════════════════════

    private void log(String client, String method, String detail) {
        String timestamp = LocalTime.now().format(DateTimeFormatter.ofPattern("HH:mm:ss"));
        String entry = String.format("[%s] CLIENT: %-12s | METHOD: %-22s | %s",
                                     timestamp, client, method, detail);
        serverLog.add(entry);
        SwingUtilities.invokeLater(() -> {
            logArea.append(entry + "\n");
            logArea.setCaretPosition(logArea.getDocument().getLength());
        });
    }

    // ═══════════════════════════  Swing Dashboard  ══════════════════════════

    private void refreshResourcePanel() {
        resourceArea.setText("");
        for (String r : sharedResources)
            resourceArea.append("  " + r + "\n");
    }

    private void buildDashboard() {
        JFrame frame = new JFrame("🖥️  CSC405 — RMI Server Dashboard");
        frame.setDefaultCloseOperation(JFrame.EXIT_ON_CLOSE);
        frame.setSize(820, 580);
        frame.setLocationRelativeTo(null);
        frame.getContentPane().setBackground(new Color(30, 30, 46));

        // Title bar
        JLabel title = new JLabel("  RMI Server  •  Listening on port 1099", JLabel.LEFT);
        title.setFont(new Font("Monospaced", Font.BOLD, 16));
        title.setForeground(new Color(137, 220, 235));
        title.setOpaque(true);
        title.setBackground(new Color(24, 24, 37));
        title.setBorder(new EmptyBorder(10, 15, 10, 0));

        // Log panel
        logArea = new JTextArea();
        logArea.setEditable(false);
        logArea.setBackground(new Color(24, 24, 37));
        logArea.setForeground(new Color(166, 227, 161));
        logArea.setFont(new Font("Monospaced", Font.PLAIN, 12));
        logArea.setBorder(new EmptyBorder(5, 8, 5, 8));
        JScrollPane logScroll = new JScrollPane(logArea);
        logScroll.setBorder(BorderFactory.createTitledBorder(
            BorderFactory.createLineBorder(new Color(137, 220, 235)),
            " 📋 Request Log ", TitledBorder.LEFT, TitledBorder.TOP,
            new Font("Dialog", Font.BOLD, 12), new Color(137, 220, 235)));

        // Shared resources panel
        resourceArea = new JTextArea();
        resourceArea.setEditable(false);
        resourceArea.setBackground(new Color(24, 24, 37));
        resourceArea.setForeground(new Color(249, 226, 175));
        resourceArea.setFont(new Font("Monospaced", Font.PLAIN, 13));
        resourceArea.setBorder(new EmptyBorder(5, 8, 5, 8));
        JScrollPane resScroll = new JScrollPane(resourceArea);
        resScroll.setPreferredSize(new Dimension(260, 0));
        resScroll.setBorder(BorderFactory.createTitledBorder(
            BorderFactory.createLineBorder(new Color(249, 226, 175)),
            " 📁 Shared Resources ", TitledBorder.LEFT, TitledBorder.TOP,
            new Font("Dialog", Font.BOLD, 12), new Color(249, 226, 175)));

        refreshResourcePanel();

        // Status bar
        JLabel status = new JLabel("  ✅ Server is ONLINE — awaiting clients...");
        status.setForeground(new Color(166, 227, 161));
        status.setFont(new Font("Dialog", Font.BOLD, 12));
        status.setOpaque(true);
        status.setBackground(new Color(24, 24, 37));
        status.setBorder(new EmptyBorder(6, 10, 6, 0));

        JSplitPane split = new JSplitPane(JSplitPane.HORIZONTAL_SPLIT, logScroll, resScroll);
        split.setDividerLocation(540);
        split.setBackground(new Color(30, 30, 46));

        frame.add(title, BorderLayout.NORTH);
        frame.add(split,  BorderLayout.CENTER);
        frame.add(status, BorderLayout.SOUTH);
        frame.setVisible(true);

        log("SYSTEM", "startup", "RMI Server started — 4 clients can now connect");
    }

    // ═══════════════════════════  Main Entry Point  ══════════════════════════

    public static void main(String[] args) {
        SwingUtilities.invokeLater(() -> {
            try {
                RMIServer server = new RMIServer();
                server.buildDashboard();

                // Start RMI registry on port 1099 and bind the server
                java.rmi.registry.LocateRegistry.createRegistry(1099);
                Naming.rebind("rmi://localhost/RMIServer", server);

                System.out.println("Server bound. Waiting for clients...");
            } catch (Exception e) {
                JOptionPane.showMessageDialog(null,
                    "Server Error: " + e.getMessage(), "Error",
                    JOptionPane.ERROR_MESSAGE);
                e.printStackTrace();
            }
        });
    }
}
